export function staticPageText(locale: string, text: string): string {
  if (locale === "en") return text;
  const dictionary = dictionaries[locale as Exclude<Locale, "en">];
  const completionDictionary = completionDictionaries[locale as Exclude<Locale, "en">];
  const waterfallDictionary = waterfallPageDictionaries[locale as Exclude<Locale, "en">];
  return (
    (locale === "fr" ? frenchGuideCompletionDictionary[text] : undefined) ??
    waterfallDictionary?.[text] ??
    completionDictionary?.[text] ??
    dictionary?.[text] ??
    guidePhraseText(locale, text)
  );
}

export function localizeStaticPage(node: ReactNode, locale: string): ReactNode {
  if (typeof node === "string") return staticPageText(locale, node);
  if (typeof node === "number" || typeof node === "boolean" || node == null) return node;
  if (Array.isArray(node)) return node.map((child) => localizeStaticPage(child, locale));
  if (!isValidElement<PropsWithText>(node)) return node;

  const nextProps: PropsWithText = {};
  if (typeof node.props.alt === "string") nextProps.alt = staticPageText(locale, node.props.alt);
  if (typeof node.props.title === "string") nextProps.title = staticPageText(locale, node.props.title);
  if (typeof node.props["aria-label"] === "string") {
    nextProps["aria-label"] = staticPageText(locale, node.props["aria-label"]);
  }

  if ("children" in node.props) {
    nextProps.children = Children.map(node.props.children, (child) =>
      localizeStaticPage(child, locale),
    );
  }

  return cloneElement(node as ReactElement<PropsWithText>, nextProps);
}
